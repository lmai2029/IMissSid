static uint32_t PWMA0timclk = 0;
static uint32_t PWMA1timclk = 0;
void TIMG0_init(uint32_t period, uint32_t prescaler){
	if (!(TIMG0->GPRCM.PWREN & GPTIMER_PWREN_ENABLE_MASK)) {
        TIMG0->GPRCM.RSTCTL = (GPTIMER_RSTCTL_KEY_UNLOCK_W | GPTIMER_RSTCTL_RESETSTKYCLR_CLR | GPTIMER_RSTCTL_RESETASSERT_ASSERT);
        TIMG0->GPRCM.PWREN = (GPTIMER_PWREN_KEY_UNLOCK_W | GPTIMER_PWREN_ENABLE_ENABLE);
    }
    
		uint32_t freq = SYSCTL_SYSCLK_getULPCLK();
		uint32_t timclk = freq/((period) * (prescaler));
		
		TIMG0->CLKSEL |= GPTIMER_CLKSEL_BUSCLK_SEL_MASK;
		TIMG0->CLKDIV |= GPTIMER_CLKDIV_RATIO_DIV_BY_1;
		TIMG0->COMMONREGS.CPS |= prescaler - 1;
		TIMG0->COUNTERREGS.LOAD = timclk - 1;
		
		TIMG0->COUNTERREGS.CTRCTL = (GPTIMER_CTRCTL_EN_ENABLED|GPTIMER_CTRCTL_CM_DOWN|
		GPTIMER_CTRCTL_CVAE_LDVAL|GPTIMER_CTRCTL_REPEAT_REPEAT_1);
		
		
		TIMG0->COMMONREGS.CCLKCTL = GPTIMER_CCLKCTL_CLKEN_ENABLED;
		TIMG6->COUNTERREGS.CTRCTL &= ~GPTIMER_CTRCTL_EN_MASK;
		
		__disable_irq();
		
		TIMG0-> CPU_INT.ICLR = GPTIMER_GEN_EVENT1_ICLR_Z_CLR; 
		TIMG0-> CPU_INT.IMASK = GPTIMER_GEN_EVENT0_IMASK_Z_SET;
		
		NVIC_EnableIRQ(TIMG0_INT_IRQn);
		__enable_irq();

}


